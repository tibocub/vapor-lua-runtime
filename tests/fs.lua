assert(vapor.caps.fs == true and type(vapor.caps.net) == "boolean")
local d = (os.getenv("TMPDIR") or ".") .. "/vlr-fs-test-" .. os.time()
assert(vapor.fs.mkdir(d))
assert(vapor.fs.stat(d).type == "dir")
local f = assert(io.open(d .. "/x.txt", "w")); f:write("hello"); f:close()
local l = vapor.fs.list(d)
assert(#l == 1 and l[1] == "x.txt")
local st = vapor.fs.stat(d .. "/x.txt")
assert(st.type == "file" and st.size == 5)
local nope, err = vapor.fs.stat(d .. "/missing")
assert(nope == nil and type(err) == "string")
assert(vapor.fs.list(d .. "/missing") == nil)
assert(os.remove(d .. "/x.txt"))
assert(vapor.fs.rmdir(d))
assert(vapor.fs.stat(d) == nil)
