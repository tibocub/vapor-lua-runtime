-- ed25519 verify with RFC 8032 test vector 1 (empty message)
local sign = require("vapor.sign")
local function hex(s) return (s:gsub("%x%x", function(h) return string.char(tonumber(h, 16)) end)) end
local pk = hex("d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a")
local sig = hex("e5564300c360ac729086e2cc806e828a84877f1eb8e5d974d873e065224901555fb8821590a33bacc61e39701cf9b46bd25bf5f0595bbe24655141438e7a100b")
assert(sign.verify(sig, "", pk) == true, "valid signature rejected")
assert(sign.verify(sig, "x", pk) == false, "wrong message accepted")
assert(sign.verify(sig:sub(1, 63) .. "\0", "", pk) == false, "damaged signature accepted")
assert(not pcall(sign.verify, "short", "", pk))
print("ok")
