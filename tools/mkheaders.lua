-- mkheaders.lua : regenerates lua/luaheaders.lua from third_party/lua/*.h (run with ./vlr tools/mkheaders.lua; `make headers`).
-- The module carries Lua's public headers so a native module can be compiled against exactly the runtime that will load it, with no install layout to find.
local names = { "lua.h", "luaconf.h", "lauxlib.h", "lualib.h" }
local out = { "-- generated by tools/mkheaders.lua from third_party/lua; do not edit. Used by vpm to build native rocks.\n",
              "-- headers.write(dir) writes the files, headers.files has their text, headers.version is the Lua release.\n",
              "local M = { files = {} }\n" }
local version
for _, n in ipairs(names) do
  local f = assert(io.open("third_party/lua/" .. n, "rb"))
  local text = f:read("a"); f:close()
  version = version or text:match('#define%s+LUA_VERSION_MAJOR%s+"(%d+)"') and (text:match('LUA_VERSION_MAJOR%s+"(%d+)"') .. "." .. text:match('LUA_VERSION_MINOR%s+"(%d+)"'))
  local level = 0
  while text:find("]" .. ("="):rep(level) .. "]", 1, true) do level = level + 1 end
  local eq = ("="):rep(level)
  out[#out + 1] = ("M.files[%q] = [%s[\n%s]%s]\n"):format(n, eq, text, eq)
end
out[#out + 1] = ('M.version = %q\n'):format(version or "")
out[#out + 1] = [[

function M.write(dir)
  for name, text in pairs(M.files) do
    local f, err = io.open(dir .. "/" .. name, "wb")
    if not f then return nil, err end
    f:write(text)
    f:close()
  end
  return true
end

return M
]]
local f = assert(io.open("lua/luaheaders.lua", "wb"))
f:write(table.concat(out))
f:close()
