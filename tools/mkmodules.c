/* mkmodules modules.conf [name...] -> vlr_modules.c (host tool). Line format: name symbol [sources/flags...] for a C module,
   name lua:path for a module that is one Lua file (embedded; @VLR@ in a path is the folder of modules.conf).
   With names, only those modules are registered. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAX 64

static char name[MAX][64], sym[MAX][512];

static void embed(const char *dir, const char *spec, int idx)
{
    char path[1024], *at;
    FILE *f;
    int c, n = 0;

    snprintf(path, sizeof path, "%s", spec);
    if ((at = strstr(path, "@VLR@")) != NULL) snprintf(at, sizeof path - (size_t)(at - path), "%s%s", dir, spec + (at - path) + 5);
    if ((f = fopen(path, "rb")) == NULL) { fprintf(stderr, "mkmodules: cannot read %s\n", path); exit(1); }
    printf("static const unsigned char lua_%d[] = {", idx);
    while ((c = fgetc(f)) != EOF) printf("%s%d,", n++ % 24 ? "" : "\n", c);
    printf("0};\n");
    fclose(f);
    printf("static int load_%d(lua_State *L)\n{\n    int n = lua_gettop(L);\n\n    if (vlr_load_embedded(L, lua_%d, sizeof lua_%d - 1, \"=%s\") != 0) return lua_error(L);\n"
           "    lua_insert(L, 1);\n    lua_call(L, n, 1);\n    return 1;\n}\n", idx, idx, idx, name[idx]);
}

int main(int argc, char **argv)
{
    char line[1024], dir[1024], *slash;
    int n = 0, i;
    FILE *f;

    if (argc < 2 || (f = fopen(argv[1], "r")) == NULL) { fprintf(stderr, "usage: mkmodules modules.conf [name...]\n"); return 1; }
    snprintf(dir, sizeof dir, "%s", argv[1]);
    if ((slash = strrchr(dir, '/')) != NULL) *slash = 0; else strcpy(dir, ".");
    while (fgets(line, sizeof line, f)) {
        int k, want = argc == 2;

        if (line[0] == '#' || sscanf(line, "%63s %511s", name[n], sym[n]) != 2) continue;
        for (k = 2; k < argc; k++) want |= strcmp(argv[k], name[n]) == 0;
        if (!want) continue;
        if (++n == MAX) { fprintf(stderr, "mkmodules: too many modules\n"); return 1; }
    }
    printf("/* generated by tools/mkmodules from modules.conf */\n#include \"lua.h\"\n#include \"lauxlib.h\"\n"
           "int vlr_load_embedded(lua_State *L, const unsigned char *src, size_t len, const char *name);\n");
    for (i = 0; i < n; i++) {
        if (strncmp(sym[i], "lua:", 4) == 0) embed(dir, sym[i] + 4, i);
        else printf("int %s(lua_State *L);\n", sym[i]);
    }
    printf("void vlr_modules_open(lua_State *L)\n{\n    luaL_getsubtable(L, LUA_REGISTRYINDEX, LUA_PRELOAD_TABLE);\n");
    for (i = 0; i < n; i++) {
        if (strncmp(sym[i], "lua:", 4) == 0) printf("    lua_pushcfunction(L, load_%d);\n", i);
        else printf("    lua_pushcfunction(L, %s);\n", sym[i]);
        printf("    lua_setfield(L, -2, \"%s\");\n", name[i]);
    }
    printf("    lua_pop(L, 1);\n}\nconst char *const vlr_builtin[] = {");
    for (i = 0; i < n; i++) printf("\"%s\", ", name[i]);
    printf("NULL};\n");
    return 0;
}
