/* mkmodules modules.conf -> vlr_modules.c (host tool). Line format: name symbol [sources/flags...] */
#include <stdio.h>
#include <string.h>

#define MAX 64

int main(int argc, char **argv)
{
    char line[1024], name[MAX][64], sym[MAX][64];
    int n = 0, i;
    FILE *f;

    if (argc != 2 || (f = fopen(argv[1], "r")) == NULL) { fprintf(stderr, "usage: mkmodules modules.conf\n"); return 1; }
    while (fgets(line, sizeof line, f)) {
        if (line[0] == '#' || sscanf(line, "%63s %63s", name[n], sym[n]) != 2) continue;
        if (++n == MAX) { fprintf(stderr, "mkmodules: too many modules\n"); return 1; }
    }
    printf("/* generated by tools/mkmodules from modules.conf */\n#include \"lua.h\"\n#include \"lauxlib.h\"\n");
    for (i = 0; i < n; i++) printf("int %s(lua_State *L);\n", sym[i]);
    printf("void vlr_modules_open(lua_State *L)\n{\n    luaL_getsubtable(L, LUA_REGISTRYINDEX, LUA_PRELOAD_TABLE);\n");
    for (i = 0; i < n; i++) printf("    lua_pushcfunction(L, %s);\n    lua_setfield(L, -2, \"%s\");\n", sym[i], name[i]);
    printf("    lua_pop(L, 1);\n}\n");
    return 0;
}
