#!/bin/sh
# Regenerates lua/cacerts.lua (module vapor.cacerts: Mozilla's trusted roots as PEM text) from https://curl.se/ca/cacert.pem.
# Used by vapor.tls where the system has no usable bundle (Windows adds it to the system store, boards have no files). Re-run to update the roots.
set -e
out=${1:-lua/cacerts.lua}
tmp=$(mktemp)
curl -fsSL https://curl.se/ca/cacert.pem -o "$tmp"
stamp=$(sed -n 's/^## Certificate data from Mozilla as of: //p' "$tmp")
{
  echo "-- vapor.cacerts: Mozilla's trusted root certificates as PEM text (from https://curl.se/ca/cacert.pem, data as of $stamp)."
  echo "-- Generated by tools/mkcacerts.sh: do not edit. Licence of the data: MPL 2.0 (Mozilla)."
  echo "return [==["
  awk '/^-----BEGIN CERTIFICATE-----/{on=1} on{print} /^-----END CERTIFICATE-----/{on=0}' "$tmp"
  echo "]==]"
} > "$out"
rm -f "$tmp"
echo "wrote $out ($(grep -c BEGIN "$out") certificates, data as of $stamp)"
